using NpgsqlTypes;

namespace PebbleAudio.Server.Data;

/// <summary>
/// A conversation as the app cut it: one or more pieces of recording segments (sync-protocol.md §2.1).
/// </summary>
public sealed class Conversation : SyncedRecord
{
	/// <summary>The app's conversation id, for example <c>conv-seg-…</c>.</summary>
	public string Id { get; set; } = "";

	public DateTimeOffset StartedAt { get; set; }

	public DateTimeOffset? EndedAt { get; set; }

	/// <summary>The IANA time zone the phone was in, for example <c>Asia/Jakarta</c>.</summary>
	public string TimeZone { get; set; } = "";

	/// <summary>The app's logical day (5 AM boundary, in <see cref="TimeZone"/>).</summary>
	public DateOnly DayKey { get; set; }

	public ConversationState State { get; set; }

	/// <summary>Why the segmenter started this conversation, for example <c>topicChange</c>.</summary>
	public string? StartReason { get; set; }

	/// <summary>True while the segmenter may still move the boundary.</summary>
	public bool Provisional { get; set; }

	public string? Title { get; set; }

	public string? Summary { get; set; }

	public List<string> Tags { get; set; } = [];

	public bool TitleEditedByUser { get; set; }

	public bool IsFinal { get; set; }

	public string? AnnotationProvider { get; set; }

	public string? AnnotationModel { get; set; }

	public ContentKind ContentKind { get; set; }

	/// <summary>What the audio was when it was not a conversation, for example <c>music</c>.</summary>
	public string? ContentDescriptor { get; set; }

	public bool MostlyQuiet { get; set; }

	public bool HasMissingAudio { get; set; }

	/// <summary>Stored audio inside the conversation, in milliseconds.</summary>
	public long RecordedMs { get; set; }

	/// <summary>
	/// The audio genuinely missing inside the conversation, in milliseconds, as the phone's History card counts it.
	/// Null from a phone before the gap change, whose total <see cref="Mcp.GapRows.MissingSeconds"/> reads from
	/// the gap records.
	/// </summary>
	public long? MissingMs { get; set; }

	public List<ConversationPiece> Pieces { get; set; } = [];

	public List<ConversationSpeaker> People { get; set; } = [];

	public List<ConversationGap> Gaps { get; set; } = [];

	/// <summary>
	/// Generated by Postgres from the title (weight A), tags and summary (B). Search combines it with
	/// <see cref="Transcript.SearchVector"/>, because a generated column cannot read another table.
	/// </summary>
	public NpgsqlTsVector SearchVector { get; set; } = null!;
}
