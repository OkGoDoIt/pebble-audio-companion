using NpgsqlTypes;

namespace PebbleAudio.Server.Data;

/// <summary>
/// A conversation's transcript, already cut to its pieces, with wall-clock times and the honest markers
/// (sync-protocol.md §2.2). It may arrive before its conversation, so there is no foreign key between them.
/// </summary>
public sealed class Transcript : SyncedRecord
{
	public string ConversationId { get; set; } = "";

	public string? SourceHash { get; set; }

	public string? Provider { get; set; }

	public string? Model { get; set; }

	public string? Language { get; set; }

	public int CharCount { get; set; }

	/// <summary>The plain joined text the server indexes.</summary>
	public string Text { get; set; } = "";

	/// <summary>What tools return as turns, in time order.</summary>
	public List<TranscriptItem> Items { get; set; } = [];

	/// <summary>Generated by Postgres from <see cref="Text"/>.</summary>
	public NpgsqlTsVector SearchVector { get; set; } = null!;
}
